// The document model: a parametric document is an ordered timeline of features
// plus a set of variables. Regeneration replays the features up to the rollback
// point. This is the backbone every later feature (sketches, extrude, …) plugs
// into.
import type { BooleanOp, PrimitiveKind } from "../kernel/types";
import type { SketchPlaneRef } from "./planes";

export type FeatureKind = PrimitiveKind;

export type Vec2 = [number, number];

/** Optional expression overlays for a sketch entity's numeric coordinates and
 *  scalars, keyed by a dot-path into the entity: "a.0"/"a.1" (line ends),
 *  "c.0"/"c.1" + "r" (circle/arc centre + radius), "start"/"end" (arc angles,
 *  **radians** — the internal unit), "p.0"/"p.1" (point/text anchor), "height"
 *  and "rotation" (text), "points.<i>.0"/"points.<i>.1" (spline). A present key
 *  is re-evaluated against the document's variable scope on every regen
 *  (`applyEntityExprs`) and overwrites the stored literal; absent keys keep their
 *  number. This is how a sketch coordinate tracks a variable (e.g. an expression
 *  "innerRad + clearance"). Derived (`derivedFrom`) entities never carry overlays
 *  — they're regenerated wholesale from their sources. */
export type EntityExprs = Record<string, string>;

/** `construction: true` marks an entity as reference geometry — used for
 *  dimensions/constraints/snapping but ignored when detecting profile regions
 *  and never extruded. `exprs` (see EntityExprs) drives coordinates from
 *  variable expressions. */
export type SketchEntity =
  | { type: "line"; id: string; a: Vec2; b: Vec2; construction?: boolean; derivedFrom?: string; exprs?: EntityExprs }
  | {
      type: "circle";
      id: string;
      c: Vec2;
      r: number;
      construction?: boolean;
      derivedFrom?: string;
      exprs?: EntityExprs;
    }
  | {
      type: "arc";
      id: string;
      c: Vec2;
      r: number;
      start: number;
      end: number;
      construction?: boolean;
      derivedFrom?: string;
      exprs?: EntityExprs;
    }
  // A smooth (interpolated) open spline through its control points. An open curve
  // — used for snapping and as a sweep path, not a region boundary.
  | { type: "spline"; id: string; points: Vec2[]; construction?: boolean; derivedFrom?: string; exprs?: EntityExprs }
  | { type: "point"; id: string; p: Vec2; construction?: boolean; derivedFrom?: string; exprs?: EntityExprs }
  // A run of text. `p` is the baseline-left anchor (u,v); `height` is the font
  // (em) size in sketch units; `rotation` (radians, default 0) turns it about
  // the anchor. Rendered as glyph outlines; not a constraint/region participant
  // (the solver and region detector skip it). `font` is reserved for future
  // per-text font choice (the bundled font is used today).
  | {
      type: "text";
      id: string;
      p: Vec2;
      value: string;
      height: number;
      rotation?: number;
      font?: string;
      construction?: boolean;
      derivedFrom?: string;
      exprs?: EntityExprs;
    };

/** A derived-geometry operation on a sketch: geometry generated FROM other
 *  sketch entities and re-computed whenever its sources change, so the result
 *  stays associative. The generated entities live in the sketch's `entities`
 *  tagged with `derivedFrom: op.id`; they are NOT free variables (the solver and
 *  constraints ignore `derivedFrom` entities) and are regenerated by
 *  `applyDerived` on every solve/regen. Deleting any generated entity removes the
 *  whole op; deleting a referenced source removes the op too. */
export type DerivedOp =
  | {
      id: string;
      kind: "offset";
      /** The source chain's entity ids (any order — re-ordered at recompute). */
      sourceIds: string[];
      /** Signed offset distance as an expression string (e.g. "5" or "wall/2"). */
      distance: string;
      /** Output edges are construction iff the whole source chain was. */
      construction?: boolean;
    }
  | {
      id: string;
      kind: "mirror";
      /** The mirror axis: a line entity id in the same sketch. */
      axisId: string;
      /** The source entity ids reflected across the axis. */
      sourceIds: string[];
    }
  | {
      id: string;
      kind: "project";
      /** The model edges/vertices this op pulls into the sketch (Onshape's
       *  "Use / project"). Unlike offset/mirror, the sources are kernel-built
       *  body geometry, so the outputs can't be regenerated by the pure
       *  `applyDerived` — they're re-projected in the app layer after each kernel
       *  build (resolved by persistent `edgeName`) and tagged `derivedFrom`. */
      refs: ProjectRef[];
    }
  | {
      id: string;
      kind: "linearPattern";
      /** The source entity ids repeated along the step vector. */
      sourceIds: string[];
      /** TOTAL instance count including the seed (expression, ≥2). */
      count: string;
      /** Per-step translation in sketch u/v, as expressions (mm). */
      dx: string;
      dy: string;
    }
  | {
      id: string;
      kind: "circularPattern";
      /** The source entity ids rotated about the center. */
      sourceIds: string[];
      /** Rotation center: an associative point reference (entity vertex /
       *  circle-arc center / a point entity via at:"c" / the sketch origin),
       *  or a raw uv coordinate for a free-standing center. */
      center: PointRef | { at: Vec2 };
      /** TOTAL instance count including the seed (expression, ≥2). */
      count: string;
      /** Total sweep in degrees (expression); "360" = full circle (equal
       *  360/count steps, no duplicate at the wrap). Any other value spreads
       *  the instances endpoints-inclusive across the sweep. */
      angle: string;
      /** Spread ±angle/2 to both sides of the seed (ignored at a full 360°). */
      symmetric?: boolean;
    };

/** A reference to a body's edge or vertex, projected into a sketch by a
 *  `project` `DerivedOp`. Edges prefer the persistent `edgeName` (stable across
 *  rebuilds); `edgeId` is the build-local fallback. Vertices have no stable
 *  identity yet, so they store their world point (best-effort — see
 *  applyProjections). */
export type ProjectRef =
  | { kind: "edge"; featureId: string; edgeName?: string; edgeId: number }
  | { kind: "vertex"; featureId: string; point: [number, number, number] };

/** A reference to a specific point in a sketch: a named vertex of an entity
 *  (a line's "a"/"b" end, a circle/arc's "c" centre), the sketch origin, or a
 *  fixed external point. Resolved to live coordinates at solve time, so it
 *  survives re-solves that move the geometry. */
export type PointRef =
  | { entity: string; at: "a" | "b" | "c" }
  | { origin: true }
  /** A fixed point in the sketch plane's uv coordinates — an EXTERNAL reference
   *  such as a solid/body vertex projected orthographically onto the sketch
   *  plane. Immovable: a coincident / point-on-line to it moves the *sketch*
   *  geometry to meet this point, never the reverse. Stored as uv (not as a
   *  live body-vertex handle) because body vertices have no stable identity
   *  across kernel rebuilds — the same best-effort model the Project tool uses. */
  | { fixed: Vec2 };

/** One side of a linear distance dimension. The choice mirrors the selection:
 *  a picked point/centre/origin → `point` (measured to that exact point); a
 *  picked line → `line` (perpendicular distance to the infinite line); a picked
 *  circle/arc → `rim` (nearest boundary, i.e. centre distance ∓ radius). So the
 *  user chooses centre-vs-rim just by what they select. */
export type DistanceRef =
  { on: "point"; ref: PointRef } | { on: "line"; entity: string } | { on: "rim"; entity: string };

/** Dimensional/geometric constraints over sketch entities (solved by planegcs).
 *  `entity`/`a`/`b` reference SketchEntity ids.
 *
 *  Every dimensional constraint carries a numeric `value` — what the solver
 *  reads — and, when the user typed something that names a variable, the `expr`
 *  it came from. `expr` is the LINK: `value` is re-evaluated from it whenever
 *  the variables change (see document/dimensionExpr.ts), so a dimension typed as
 *  `w` follows `w` instead of freezing at whatever `w` happened to be. Absent on
 *  a plainly-numeric dimension (and on every document written before this
 *  existed), which simply never moves on its own. */
export type SketchConstraint =
  | { id: string; type: "horizontal"; entity: string }
  | { id: string; type: "vertical"; entity: string }
  | { id: string; type: "parallel"; a: string; b: string }
  | { id: string; type: "perpendicular"; a: string; b: string }
  | { id: string; type: "equal"; a: string; b: string }
  | { id: string; type: "distance"; entity: string; value: number; expr?: string }
  // A linear distance between two elements (point/line/rim on each side) — see
  // DistanceRef. `value` is the natural measure for the pair (straight,
  // perpendicular, or rim gap). This is the general dimension the single-entity
  // `distance` (a line's own length) is a special case of.
  | { id: string; type: "distanceBetween"; a: DistanceRef; b: DistanceRef; value: number; expr?: string }
  | { id: string; type: "radius"; entity: string; value: number; expr?: string }
  | { id: string; type: "angle"; a: string; b: string; value: number; expr?: string }
  // Tangent between a line+circle or two circles (entity ids).
  | { id: string; type: "tangent"; a: string; b: string }
  // Two points made coincident (one may be the sketch origin, which anchors
  // the other point there).
  | { id: string; type: "coincident"; a: PointRef; b: PointRef }
  // A point (entity vertex or origin) constrained to lie on a line entity.
  | { id: string; type: "pointOnLine"; point: PointRef; line: string }
  // A point constrained to lie ON the rim of a circle (or arc) — what a drawn
  // endpoint snapped to a circle's edge gets, so it follows the rim when the
  // circle is moved or re-dimensioned instead of staying where it was drawn.
  | { id: string; type: "pointOnCircle"; point: PointRef; circle: string }
  // A point constrained to the midpoint of a line, or the mid-arc point of an arc.
  | { id: string; type: "midpoint"; point: PointRef; target: string };

interface FeatureBase {
  id: string;
  name: string;
  suppressed: boolean;
}

/** A primitive solid (box/cylinder/sphere) — maps 1:1 to a kernel primitive. */
export interface PrimitiveFeature extends FeatureBase {
  type: "primitive";
  kind: FeatureKind;
  /** param name -> expression string (e.g. "40", or "width * 2"). */
  params: Record<string, string>;
  /** Display color (0xRRGGBB), assigned once at creation from the pastel bank. */
  color: number;
  /** Display opacity, 0 (invisible) – 1 (opaque). User-adjustable in the solids list. */
  opacity: number;
  /** Hidden (not rendered/pickable) — a view toggle, distinct from suppress. */
  hidden?: boolean;
}

/** A 2D sketch on a datum plane. Produces no solid on its own; it's a profile
 *  source consumed by extrude (and later revolve/sweep). */
export interface SketchFeature extends FeatureBase {
  type: "sketch";
  plane: SketchPlaneRef;
  entities: SketchEntity[];
  constraints: SketchConstraint[];
  /** Associative derived-geometry ops (offset/mirror/project). Their output
   *  entities live in `entities` tagged `derivedFrom`: offset/mirror are
   *  regenerated by `applyDerived` (pure, from sibling entities); project is
   *  re-projected in the app layer after each kernel build (from body edges). */
  derived?: DerivedOp[];
}

/** How an extrude combines with the running body set. */
export type ExtrudeMode = "new" | "add" | "remove";

/** How far an extrude reaches: a fixed `distance` one way ("blind"), `distance`
 *  split evenly both ways of the profile ("symmetric"), far enough to fully
 *  clear the target body regardless of its shape ("throughAll" — add/remove
 *  only; a target-less extrude falls back to blind using `distance`), up to
 *  the plane of a chosen target face ("upToFace" — the extrude's `upTo` face
 *  reference drives both the distance and direction; `distance`/`flip` ignored),
 *  or up to the nearest face of the target body met travelling in the
 *  flip-adjusted direction ("upToNext" — add/remove only; `flip` picks the
 *  direction, `distance` ignored). */
export type ExtrudeExtent = "blind" | "symmetric" | "throughAll" | "upToFace" | "upToNext";

/** A planar face of an earlier body, used as the "up to face" extrude target.
 *  `faceName` is the persistent topological name (preferred, stable across
 *  rebuilds); `center` + `normal` are the geometric fingerprint the kernel
 *  falls back to (scored match, rejected when implausible) when an upstream
 *  edit renamed the face. */
export interface UpToFaceRef {
  /** The feature whose body owns the face. */
  featureId: string;
  faceName?: string;
  center: [number, number, number];
  /** Unit normal at pick time (planar faces only). */
  normal?: [number, number, number];
}

/** Geometric fingerprint of a picked edge, stored alongside its persistent
 *  name so the kernel can re-match the edge when an upstream edit renamed it
 *  (`mid` is the edge's bounding-box centre; `length` its arc length). */
export interface EdgeRef {
  name: string;
  mid?: [number, number, number];
  length?: number;
}

/** Geometric fingerprint of a picked FACE, stored alongside its persistent name
 *  so the kernel can re-match it when an upstream edit renamed it (`center` is
 *  the face's centroid; `normal` is present for planar faces only). */
export interface FaceRef {
  name: string;
  center?: [number, number, number];
  normal?: [number, number, number];
}

/** What an extrude pulls: a closed region of a sketch, a planar face of an
 *  existing body (referenced by the feature that produced it + the face id), or a
 *  `text` sketch entity (baked to glyph wires with correct counters/holes by the
 *  kernel). */
export type ExtrudeProfile =
  | { kind: "sketchRegion"; sketchId: string; regionId: string }
  // A body face. `faceName` is the persistent topological name (preferred,
  // stable across rebuilds); `faceId` is the build-local hash from selection and
  // `center` the centroid — both kept as fallback when there's no name yet.
  | {
      kind: "bodyFace";
      featureId: string;
      faceId: number;
      faceName?: string;
      center: [number, number, number];
      normal?: [number, number, number];
    }
  // A run of text in a sketch (a `text` entity). The kernel re-bakes the glyph
  // wires from the entity's value/height/rotation/anchor each rebuild, so editing
  // the text re-extrudes parametrically.
  | { kind: "sketchText"; sketchId: string; textId: string };

/** Extrude a sketch region or a body face into a solid. (Phase 3.) */
export interface ExtrudeFeature extends FeatureBase {
  type: "extrude";
  /** Everything this extrude pulls, in pick order. Several profiles are ONE
   *  feature — the dialog that made them reopens with all of them, and a "new"
   *  extrude whose profiles are disjoint simply lands as several parts (see
   *  document/parts.ts). Documents written when an extrude held a single
   *  `profile` are lifted to a one-element list on load (migrateDocument). */
  profiles: ExtrudeProfile[];
  /** Blind/symmetric distance, as an expression string (e.g. "10" or "height/2").
   *  Ignored by "throughAll" once it resolves a target. */
  distance: string;
  /** Reverse the extrusion direction (against the profile normal). No effect
   *  when extent is "symmetric" (both directions are always extruded). */
  flip: boolean;
  extent: ExtrudeExtent;
  mode: ExtrudeMode;
  /** For add/remove: which body a profile that has none of its own — a sketch
   *  region or text — fuses into / cuts from. A profile taken from a BODY FACE
   *  ignores this and acts on the part it grew from, so extruding faces of two
   *  different parts in one go modifies each of them rather than dumping both
   *  into whichever body happened to be picked first. */
  targetId?: string;
  /** For extent "upToFace": the target face the extrude reaches up to. */
  upTo?: UpToFaceRef;
  /** Display color/opacity for a "new" extrusion's body (like primitives).
   *  Ignored when the extrude is add/remove (it modifies an existing body). */
  color: number;
  opacity: number;
  hidden?: boolean;
}

/** A union/subtract/intersect of two or more earlier solid bodies, referenced
 *  by id. Operand order matters for subtract (first = base, rest = tools). */
export interface BooleanFeature extends FeatureBase {
  type: "boolean";
  op: BooleanOp;
  operands: string[];
  /** Inherited from the first operand at creation time — see document/colors.ts. */
  color: number;
  opacity: number;
  hidden?: boolean;
}

/** Chamfer/fillet a set of edges of a body (referenced by persistent name). */
/** Everything one dress-up does to ONE body. A chamfer picked across three
 *  parts is a single feature with three of these — the dialog that made it
 *  reopens with all of them, and a rebuild dresses each body from its own
 *  reference list (edge names only mean anything on the body they came from). */
export interface DressUpTargetSpec {
  /** The body whose edges are dressed (the part id that produced it). */
  targetId: string;
  /** Persistent names of the edges to chamfer/fillet. */
  edges: string[];
  /** Geometric fingerprints for `edges` (parallel array), used to re-match an
   *  edge whose name churned after an upstream edit. Absent on legacy docs. */
  edgeRefs?: EdgeRef[];
  /** Persistent names of whole FACES to dress: every boundary edge of the face
   *  is chamfered/filleted. */
  faces?: string[];
  /** Geometric fingerprints for `faces` (parallel array). */
  faceRefs?: FaceRef[];
}

export interface DressUpFeature extends FeatureBase {
  type: "dressup";
  op: "chamfer" | "fillet";
  /** The bodies this dress-up acts on, one entry each. Documents written when a
   *  dress-up held a single target (`targetId`/`edges`/`faces` at the top level)
   *  are lifted to a one-element list on load (migrateDocument). */
  targets: DressUpTargetSpec[];
  /** Chamfer distance / fillet radius, as an expression string — one size for
   *  every target. */
  size: string;
  /** Chamfer only: the bevel angle in degrees, measured from the reference face
   *  (the face `size` runs along). 45 is the symmetric chamfer; absent ⇒ 45,
   *  which is what documents written before this field always produced. */
  angle?: string;
  /** Chamfer only: take the OTHER of the edge's two adjacent faces as the
   *  reference for `size`/`angle`. No effect at 45° (the bevel is symmetric). */
  flip?: boolean;
}

/** Hollow out a body: remove the picked faces (they become openings) and leave
 *  a wall of `thickness` around what remains. Zero removed faces makes a fully
 *  sealed hollow shell (no opening). Faces are referenced by persistent name,
 *  with a parallel `faceRefs` fingerprint array for geometric re-matching after
 *  an upstream edit churns names — same shape as `DressUpFeature.edgeRefs`. */
export interface ShellFeature extends FeatureBase {
  type: "shell";
  /** The body being hollowed (the feature id that produced it). */
  targetId: string;
  /** Persistent names of the faces to remove (open up). */
  faces: string[];
  /** Geometric fingerprints for `faces` (parallel array). */
  faceRefs?: FaceRef[];
  /** Wall thickness, as an expression string. The wall grows inward from the
   *  kept faces (the outside dimensions of the body are preserved). */
  thickness: string;
}

/** How a reference plane is placed. Older documents stored only offset planes and
 *  have no `method`, so a missing method is treated as "offset". */
export type PlaneMethod = "offset" | "midplane" | "angle" | "through";

/** A user-created reference / construction plane. Placement methods:
 *  - offset: parallel to `base`, by signed `offset` distance along its normal;
 *  - midplane: halfway between `base` and `refB`;
 *  - angle: `base` hinged on its u/v axis (`angleAxis`) by `angle` degrees;
 *  - through: through three world `points`. */
export interface PlaneFeature extends FeatureBase {
  type: "plane";
  /** Placement method; absent on legacy docs ⇒ treated as "offset". */
  method?: PlaneMethod;
  /** offset / angle base, or the first reference of a midplane. */
  base: SketchPlaneRef;
  /** Offset distance along the base's normal, as an expression string. */
  offset: string;
  /** Midplane: the second reference. */
  refB?: SketchPlaneRef;
  /** At-angle: which base axis to hinge on, and the tilt in degrees (expression). */
  angleAxis?: "u" | "v";
  angle?: string;
  /** Through-geometry: three world points the plane passes through. */
  points?: [number, number, number][];
  /** Display color (0xRRGGBB), assigned once at creation from the pastel bank. */
  color: number;
  /** Hidden (not rendered/pickable) — a view toggle. Unlike suppress it leaves
   *  the plane in the model, so sketches and features built on it still resolve. */
  hidden?: boolean;
}

/** A transform (translate + rotate + uniform scale) applied to a body in place.
 *  Like a rigid motion, a similarity (uniform scale) doesn't alter topology, so
 *  the body keeps its identity AND its persistent topological names — downstream
 *  features still reference it. The body keeps the id of the feature that
 *  produced it (like chamfer/fillet). Phase 5.5. */
export interface TransformFeature extends FeatureBase {
  type: "transform";
  /** The body being moved (the feature id that produced it). */
  targetId: string;
  /** Translation along world X/Y/Z, as expression strings (mm). */
  tx: string;
  ty: string;
  tz: string;
  /** Rotation angle in degrees (expression), about `axis` through `pivot`. */
  angle: string;
  /** World axis the rotation turns about. */
  axis: "x" | "y" | "z";
  /** Uniform scale factor (expression) about `pivot`, applied BEFORE the
   *  rotation and translation. 1 = unscaled. Uniform only: OCCT's non-uniform
   *  BRepBuilderAPI_GTransform isn't bound in this wasm build, and a similarity
   *  is also what keeps the topology (and its names) intact. */
  scale: string;
  /** Pivot the rotation turns around and the scale grows from (world space),
   *  baked at creation from the target body's centroid so the gizmo and kernel
   *  agree. */
  pivot: [number, number, number];
  /** Keep the original: when true the transform produces a NEW body (a moved
   *  copy, keyed by this feature) and leaves the target untouched; when false it
   *  moves the target in place (keeping its id). */
  copy: boolean;
  /** Appearance of the copied body (used only when `copy`). */
  color: number;
  opacity: number;
  hidden?: boolean;
}

/** A body face armed as a revolve axis. `faceName` is the persistent topological
 *  name (preferred, stable across rebuilds); `center` is the centroid fallback
 *  (mirrors `UpToFaceRef`/`bodyFace`). The kernel resolves it to a line axis at
 *  build time: a planar face → where its plane meets the profile plane; a
 *  cylindrical/conical face → that surface's own central axis. */
export interface RevolveAxisFace {
  featureId: string;
  faceName?: string;
  faceId: number;
  center: [number, number, number];
  /** Unit normal at pick time (planar faces only) — part of the geometric
   *  fingerprint used to re-match the face if its name churns. */
  normal?: [number, number, number];
}

/** A body EDGE armed as a revolve axis: a straight edge IS a line, so it needs
 *  no intersection — the kernel reads its two endpoints. `edgeName` is the
 *  persistent topological name (preferred); `mid`/`length` are the geometric
 *  fingerprint it's re-matched by when an upstream edit renames it (the same
 *  pair dress-ups store, see `EdgeRef`). */
export interface RevolveAxisEdge {
  featureId: string;
  edgeName?: string;
  edgeId: number;
  mid?: [number, number, number];
  length?: number;
}

/** The rotation axis of a revolve. One of:
 *  - a sketch line entity (its two endpoints define the axis);
 *  - a plane, where the axis is the line the plane makes with the profile plane;
 *  - a body face (planar → plane ∩ profile plane; cylinder/cone → surface axis);
 *  - a straight body edge (the edge itself is the axis line). */
export type RevolveAxis =
  | { sketchId: string; entityId: string }
  | { plane: SketchPlaneRef }
  | { face: RevolveAxisFace }
  | { edge: RevolveAxisEdge };

/** What a revolve spins: a closed sketch region, or a PLANAR face of an existing
 *  body — the same two reference shapes extrude accepts (text is excluded: glyph
 *  runs are many disjoint faces, which a revolve has no sensible axis story for).
 *  A face profile makes the revolve depend on that body, exactly like an extrude
 *  pulled off a face. */
export type RevolveProfile = Extract<ExtrudeProfile, { kind: "sketchRegion" } | { kind: "bodyFace" }>;

/** Revolve a sketch region or planar body face around an axis (a sketch line, a
 *  plane, or a body face) to make a solid. Like extrude, a body *producer*.
 *  (Phase 6.) */
export interface RevolveFeature extends FeatureBase {
  type: "revolve";
  /** The closed region (or planar body face) to revolve. */
  profile: RevolveProfile;
  /** The rotation axis: a sketch line, or a plane (axis = plane ∩ profile plane). */
  axis: RevolveAxis;
  /** Revolve angle in degrees, as an expression (e.g. "360" or "angle/2").
   *  A full revolve is simply `angle` "360". */
  angle: string;
  /** Revolve split evenly to both sides of the profile plane (the solid spans
   *  −angle/2 .. +angle/2) instead of one direction. Irrelevant at a full 360°. */
  symmetric: boolean;
  color: number;
  opacity: number;
  hidden?: boolean;
}

/** A direction for a linear body pattern: a world axis, or a sketch line entity
 *  (its two endpoints baked to a world direction at resolve time, so the pattern
 *  follows when the line is re-drawn/re-solved). */
export type PatternDirRef = { world: "x" | "y" | "z" } | { sketchId: string; entityId: string };

/** A circular body pattern's rotation axis: a world axis (through the origin),
 *  a sketch line entity, or a body face (cylindrical/conical → that surface's
 *  own central axis, resolved in the kernel; reuses revolve's face reference —
 *  planar faces are rejected since a pattern has no profile plane to intersect). */
export type PatternAxisRef =
  { world: "x" | "y" | "z" } | { sketchId: string; entityId: string } | { face: RevolveAxisFace };

/** Repeat a body as rigid copies — a linear run/grid or a circular ring. The
 *  copies are compounded into ONE new body keyed by this feature and the seed
 *  body is left untouched (delete/suppress the pattern ⇒ back to the seed, like
 *  Mirror). Counts are TOTAL instances including the seed (expressions, ≥2).
 *  Circular `angle` "360" = full circle (equal 360/count steps, no duplicate at
 *  the wrap); any other sweep spreads the instances endpoints-inclusive, and
 *  `symmetric` re-centers the spread on the seed (±angle/2). There is no radius
 *  input — instances are rotations of the seed about the axis, so the radius is
 *  wherever the seed already sits. (Phase 5.) */
export interface PatternFeature extends FeatureBase {
  type: "pattern";
  kind: "linear" | "circular";
  /** The body being repeated (the feature id that produced it). */
  targetId: string;
  /** Linear: first direction + total count + instance-to-instance spacing. */
  dir1?: PatternDirRef;
  count1?: string;
  spacing1?: string;
  flip1?: boolean;
  /** Linear: optional second direction ⇒ a count1×count2 grid. */
  dir2?: PatternDirRef;
  count2?: string;
  spacing2?: string;
  flip2?: boolean;
  /** Circular: rotation axis + total count + sweep. */
  axis?: PatternAxisRef;
  count?: string;
  angle?: string;
  symmetric?: boolean;
  color: number;
  opacity: number;
  hidden?: boolean;
}

/** Mirror a body across a plane, producing a new (reflected) body. The original
 *  is kept. The mirror plane is a datum / reference plane / planar face. */
export interface MirrorFeature extends FeatureBase {
  type: "mirror";
  /** The body being mirrored (the feature id that produced it). */
  targetId: string;
  /** The mirror plane. */
  plane: SketchPlaneRef;
  color: number;
  opacity: number;
  hidden?: boolean;
}

/** Sweep a sketch region (profile) along a path entity (line/arc/spline) in a
 *  sketch. A body *producer* like extrude/revolve. (Phase 6.) */
export interface SweepFeature extends FeatureBase {
  type: "sweep";
  /** The closed sketch region to sweep. */
  profile: { sketchId: string; regionId: string };
  /** The path/spine: a single open entity (line, arc, or spline) in a sketch. */
  path: { sketchId: string; entityId: string };
  color: number;
  opacity: number;
  hidden?: boolean;
}

/** Loft through two or more sketch regions (in timeline order) to make a solid.
 *  A body *producer*. (Phase 6.) */
export interface LoftFeature extends FeatureBase {
  type: "loft";
  /** Ordered closed sections to loft through (≥2). */
  profiles: { sketchId: string; regionId: string }[];
  color: number;
  opacity: number;
  hidden?: boolean;
}

/** A body imported from a CAD file (STEP for now). A body *producer*, like a
 *  primitive. The raw file text is stored on the feature (JSON-serializable, so
 *  it round-trips through IndexedDB / `.json`). */
export interface ImportFeature extends FeatureBase {
  type: "import";
  format: "step";
  /** Raw STEP file contents. */
  source: string;
  color: number;
  opacity: number;
  hidden?: boolean;
}

export type Feature =
  | PrimitiveFeature
  | SketchFeature
  | ExtrudeFeature
  | DressUpFeature
  | ShellFeature
  | BooleanFeature
  | PlaneFeature
  | TransformFeature
  | MirrorFeature
  | PatternFeature
  | RevolveFeature
  | SweepFeature
  | LoftFeature
  | ImportFeature;

export interface Variable {
  id: string;
  name: string;
  expression: string;
}

/** Per-part appearance for the 2nd, 3rd… part of a feature — the ones that
 *  can't use the feature's own fields because a sibling already does. Every
 *  field is optional: a part with none of them simply looks like its feature
 *  (see document/parts.ts). */
export interface PartOverride {
  name?: string;
  color?: number;
  opacity?: number;
  hidden?: boolean;
}

export interface Document {
  features: Feature[];
  variables: Variable[];
  /** Appearance overrides keyed by PART id (`<featureId>#<n>`). Absent on every
   *  document written before a feature could produce more than one part. */
  parts?: Record<string, PartOverride>;
  /** Number of features evaluated, 0..features.length. Features at index >=
   *  rollbackIndex are "rolled back" (not regenerated). */
  rollbackIndex: number;
}
