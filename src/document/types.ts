// The document model: a parametric document is an ordered timeline of features
// plus a set of variables. Regeneration replays the features up to the rollback
// point. This is the backbone every later feature (sketches, extrude, …) plugs
// into.
import type { BooleanOp, PrimitiveKind } from "../kernel/types";
import type { SketchPlaneRef } from "./planes";

export type FeatureKind = PrimitiveKind;

export type Vec2 = [number, number];

/** `construction: true` marks an entity as reference geometry — used for
 *  dimensions/constraints/snapping but ignored when detecting profile regions
 *  and never extruded. */
export type SketchEntity =
  | { type: "line"; id: string; a: Vec2; b: Vec2; construction?: boolean; derivedFrom?: string }
  | { type: "circle"; id: string; c: Vec2; r: number; construction?: boolean; derivedFrom?: string }
  | { type: "arc"; id: string; c: Vec2; r: number; start: number; end: number; construction?: boolean; derivedFrom?: string }
  // A smooth (interpolated) open spline through its control points. An open curve
  // — used for snapping and as a sweep path, not a region boundary.
  | { type: "spline"; id: string; points: Vec2[]; construction?: boolean; derivedFrom?: string }
  | { type: "point"; id: string; p: Vec2; construction?: boolean; derivedFrom?: string }
  // A run of text. `p` is the baseline-left anchor (u,v); `height` is the font
  // (em) size in sketch units; `rotation` (radians, default 0) turns it about
  // the anchor. Rendered as glyph outlines; not a constraint/region participant
  // (the solver and region detector skip it). `font` is reserved for future
  // per-text font choice (the bundled font is used today).
  | { type: "text"; id: string; p: Vec2; value: string; height: number; rotation?: number; font?: string; construction?: boolean; derivedFrom?: string };

/** A derived-geometry operation on a sketch: geometry generated FROM other
 *  sketch entities and re-computed whenever its sources change, so the result
 *  stays associative. The generated entities live in the sketch's `entities`
 *  tagged with `derivedFrom: op.id`; they are NOT free variables (the solver and
 *  constraints ignore `derivedFrom` entities) and are regenerated by
 *  `applyDerived` on every solve/regen. Deleting any generated entity removes the
 *  whole op; deleting a referenced source removes the op too. */
export type DerivedOp =
  | {
      id: string;
      kind: "offset";
      /** The source chain's entity ids (any order — re-ordered at recompute). */
      sourceIds: string[];
      /** Signed offset distance as an expression string (e.g. "5" or "wall/2"). */
      distance: string;
      /** Output edges are construction iff the whole source chain was. */
      construction?: boolean;
    }
  | {
      id: string;
      kind: "mirror";
      /** The mirror axis: a line entity id in the same sketch. */
      axisId: string;
      /** The source entity ids reflected across the axis. */
      sourceIds: string[];
    }
  | {
      id: string;
      kind: "project";
      /** The model edges/vertices this op pulls into the sketch (Onshape's
       *  "Use / project"). Unlike offset/mirror, the sources are kernel-built
       *  body geometry, so the outputs can't be regenerated by the pure
       *  `applyDerived` — they're re-projected in the app layer after each kernel
       *  build (resolved by persistent `edgeName`) and tagged `derivedFrom`. */
      refs: ProjectRef[];
    };

/** A reference to a body's edge or vertex, projected into a sketch by a
 *  `project` `DerivedOp`. Edges prefer the persistent `edgeName` (stable across
 *  rebuilds); `edgeId` is the build-local fallback. Vertices have no stable
 *  identity yet, so they store their world point (best-effort — see
 *  applyProjections). */
export type ProjectRef =
  | { kind: "edge"; featureId: string; edgeName?: string; edgeId: number }
  | { kind: "vertex"; featureId: string; point: [number, number, number] };

/** A reference to a specific point in a sketch: a named vertex of an entity
 *  (a line's "a"/"b" end, a circle/arc's "c" centre), or the sketch origin.
 *  Resolved to live coordinates at solve time, so it survives re-solves that
 *  move the geometry. */
export type PointRef =
  | { entity: string; at: "a" | "b" | "c" }
  | { origin: true };

/** Dimensional/geometric constraints over sketch entities (solved by planegcs).
 *  `entity`/`a`/`b` reference SketchEntity ids. */
export type SketchConstraint =
  | { id: string; type: "horizontal"; entity: string }
  | { id: string; type: "vertical"; entity: string }
  | { id: string; type: "parallel"; a: string; b: string }
  | { id: string; type: "perpendicular"; a: string; b: string }
  | { id: string; type: "equal"; a: string; b: string }
  | { id: string; type: "distance"; entity: string; value: number }
  | { id: string; type: "radius"; entity: string; value: number }
  | { id: string; type: "angle"; a: string; b: string; value: number }
  // Tangent between a line+circle or two circles (entity ids).
  | { id: string; type: "tangent"; a: string; b: string }
  // Two points made coincident (one may be the sketch origin, which anchors
  // the other point there).
  | { id: string; type: "coincident"; a: PointRef; b: PointRef }
  // A point (entity vertex or origin) constrained to lie on a line entity.
  | { id: string; type: "pointOnLine"; point: PointRef; line: string }
  // A point constrained to the midpoint of a line, or the mid-arc point of an arc.
  | { id: string; type: "midpoint"; point: PointRef; target: string };

interface FeatureBase {
  id: string;
  name: string;
  suppressed: boolean;
}

/** A primitive solid (box/cylinder/sphere) — maps 1:1 to a kernel primitive. */
export interface PrimitiveFeature extends FeatureBase {
  type: "primitive";
  kind: FeatureKind;
  /** param name -> expression string (e.g. "40", or "width * 2"). */
  params: Record<string, string>;
  /** Display color (0xRRGGBB), assigned once at creation from the pastel bank. */
  color: number;
  /** Display opacity, 0 (invisible) – 1 (opaque). User-adjustable in the solids list. */
  opacity: number;
  /** Hidden (not rendered/pickable) — a view toggle, distinct from suppress. */
  hidden?: boolean;
}

/** A 2D sketch on a datum plane. Produces no solid on its own; it's a profile
 *  source consumed by extrude (and later revolve/sweep). */
export interface SketchFeature extends FeatureBase {
  type: "sketch";
  plane: SketchPlaneRef;
  entities: SketchEntity[];
  constraints: SketchConstraint[];
  /** Associative derived-geometry ops (offset/mirror/project). Their output
   *  entities live in `entities` tagged `derivedFrom`: offset/mirror are
   *  regenerated by `applyDerived` (pure, from sibling entities); project is
   *  re-projected in the app layer after each kernel build (from body edges). */
  derived?: DerivedOp[];
}

/** How an extrude combines with the running body set. */
export type ExtrudeMode = "new" | "add" | "remove";

/** How far an extrude reaches: a fixed `distance` one way ("blind"), `distance`
 *  split evenly both ways of the profile ("symmetric"), far enough to fully
 *  clear the target body regardless of its shape ("throughAll" — add/remove
 *  only; a target-less extrude falls back to blind using `distance`), or up to
 *  the plane of a chosen target face ("upToFace" — the extrude's `upTo` face
 *  reference drives both the distance and direction; `distance`/`flip` ignored). */
export type ExtrudeExtent = "blind" | "symmetric" | "throughAll" | "upToFace";

/** A planar face of an earlier body, used as the "up to face" extrude target.
 *  `faceName` is the persistent topological name (preferred, stable across
 *  rebuilds); `center` + `normal` are the geometric fingerprint the kernel
 *  falls back to (scored match, rejected when implausible) when an upstream
 *  edit renamed the face. */
export interface UpToFaceRef {
  /** The feature whose body owns the face. */
  featureId: string;
  faceName?: string;
  center: [number, number, number];
  /** Unit normal at pick time (planar faces only). */
  normal?: [number, number, number];
}

/** Geometric fingerprint of a picked edge, stored alongside its persistent
 *  name so the kernel can re-match the edge when an upstream edit renamed it
 *  (`mid` is the edge's bounding-box centre; `length` its arc length). */
export interface EdgeRef {
  name: string;
  mid?: [number, number, number];
  length?: number;
}

/** What an extrude pulls: a closed region of a sketch, a planar face of an
 *  existing body (referenced by the feature that produced it + the face id), or a
 *  `text` sketch entity (baked to glyph wires with correct counters/holes by the
 *  kernel). */
export type ExtrudeProfile =
  | { kind: "sketchRegion"; sketchId: string; regionId: string }
  // A body face. `faceName` is the persistent topological name (preferred,
  // stable across rebuilds); `faceId` is the build-local hash from selection and
  // `center` the centroid — both kept as fallback when there's no name yet.
  | { kind: "bodyFace"; featureId: string; faceId: number; faceName?: string; center: [number, number, number]; normal?: [number, number, number] }
  // A run of text in a sketch (a `text` entity). The kernel re-bakes the glyph
  // wires from the entity's value/height/rotation/anchor each rebuild, so editing
  // the text re-extrudes parametrically.
  | { kind: "sketchText"; sketchId: string; textId: string };

/** Extrude a sketch region or a body face into a solid. (Phase 3.) */
export interface ExtrudeFeature extends FeatureBase {
  type: "extrude";
  profile: ExtrudeProfile;
  /** Blind/symmetric distance, as an expression string (e.g. "10" or "height/2").
   *  Ignored by "throughAll" once it resolves a target. */
  distance: string;
  /** Reverse the extrusion direction (against the profile normal). No effect
   *  when extent is "symmetric" (both directions are always extruded). */
  flip: boolean;
  extent: ExtrudeExtent;
  mode: ExtrudeMode;
  /** For add/remove: the body (by feature id) to fuse into / cut from. */
  targetId?: string;
  /** For extent "upToFace": the target face the extrude reaches up to. */
  upTo?: UpToFaceRef;
  /** Display color/opacity for a "new" extrusion's body (like primitives).
   *  Ignored when the extrude is add/remove (it modifies an existing body). */
  color: number;
  opacity: number;
  hidden?: boolean;
}

/** A union/subtract/intersect of two or more earlier solid bodies, referenced
 *  by id. Operand order matters for subtract (first = base, rest = tools). */
export interface BooleanFeature extends FeatureBase {
  type: "boolean";
  op: BooleanOp;
  operands: string[];
  /** Inherited from the first operand at creation time — see document/colors.ts. */
  color: number;
  opacity: number;
  hidden?: boolean;
}

/** Chamfer/fillet a set of edges of a body (referenced by persistent name). */
export interface DressUpFeature extends FeatureBase {
  type: "dressup";
  op: "chamfer" | "fillet";
  /** The body whose edges are dressed (the feature id that produced it). */
  targetId: string;
  /** Persistent names of the edges to chamfer/fillet. */
  edges: string[];
  /** Geometric fingerprints for `edges` (parallel array), used to re-match an
   *  edge whose name churned after an upstream edit. Absent on legacy docs. */
  edgeRefs?: EdgeRef[];
  /** Chamfer distance / fillet radius, as an expression string. */
  size: string;
}

/** How a reference plane is placed. Older documents stored only offset planes and
 *  have no `method`, so a missing method is treated as "offset". */
export type PlaneMethod = "offset" | "midplane" | "angle" | "through";

/** A user-created reference / construction plane. Placement methods:
 *  - offset: parallel to `base`, by signed `offset` distance along its normal;
 *  - midplane: halfway between `base` and `refB`;
 *  - angle: `base` hinged on its u/v axis (`angleAxis`) by `angle` degrees;
 *  - through: through three world `points`. */
export interface PlaneFeature extends FeatureBase {
  type: "plane";
  /** Placement method; absent on legacy docs ⇒ treated as "offset". */
  method?: PlaneMethod;
  /** offset / angle base, or the first reference of a midplane. */
  base: SketchPlaneRef;
  /** Offset distance along the base's normal, as an expression string. */
  offset: string;
  /** Midplane: the second reference. */
  refB?: SketchPlaneRef;
  /** At-angle: which base axis to hinge on, and the tilt in degrees (expression). */
  angleAxis?: "u" | "v";
  angle?: string;
  /** Through-geometry: three world points the plane passes through. */
  points?: [number, number, number][];
  /** Display color (0xRRGGBB), assigned once at creation from the pastel bank. */
  color: number;
}

/** A rigid transform (translate + rotate) applied to a body in place. A rigid
 *  motion doesn't alter topology, so the body keeps its identity AND its
 *  persistent topological names — downstream features still reference it. The
 *  body keeps the id of the feature that produced it (like chamfer/fillet).
 *  Phase 5.5. */
export interface TransformFeature extends FeatureBase {
  type: "transform";
  /** The body being moved (the feature id that produced it). */
  targetId: string;
  /** Translation along world X/Y/Z, as expression strings (mm). */
  tx: string;
  ty: string;
  tz: string;
  /** Rotation angle in degrees (expression), about `axis` through `pivot`. */
  angle: string;
  /** World axis the rotation turns about. */
  axis: "x" | "y" | "z";
  /** Pivot the rotation turns around (world space), baked at creation from the
   *  target body's centroid so the gizmo and kernel agree. */
  pivot: [number, number, number];
  /** Keep the original: when true the transform produces a NEW body (a moved
   *  copy, keyed by this feature) and leaves the target untouched; when false it
   *  moves the target in place (keeping its id). */
  copy: boolean;
  /** Appearance of the copied body (used only when `copy`). */
  color: number;
  opacity: number;
  hidden?: boolean;
}

/** A body face armed as a revolve axis. `faceName` is the persistent topological
 *  name (preferred, stable across rebuilds); `center` is the centroid fallback
 *  (mirrors `UpToFaceRef`/`bodyFace`). The kernel resolves it to a line axis at
 *  build time: a planar face → where its plane meets the profile plane; a
 *  cylindrical/conical face → that surface's own central axis. */
export interface RevolveAxisFace {
  featureId: string;
  faceName?: string;
  faceId: number;
  center: [number, number, number];
  /** Unit normal at pick time (planar faces only) — part of the geometric
   *  fingerprint used to re-match the face if its name churns. */
  normal?: [number, number, number];
}

/** The rotation axis of a revolve. One of:
 *  - a sketch line entity (its two endpoints define the axis);
 *  - a plane, where the axis is the line the plane makes with the profile plane;
 *  - a body face (planar → plane ∩ profile plane; cylinder/cone → surface axis). */
export type RevolveAxis =
  | { sketchId: string; entityId: string }
  | { plane: SketchPlaneRef }
  | { face: RevolveAxisFace };

/** Revolve a sketch region around an axis (a sketch line, or a plane) to make a
 *  solid. Like extrude, a body *producer*. (Phase 6.) */
export interface RevolveFeature extends FeatureBase {
  type: "revolve";
  /** The closed sketch region to revolve. */
  profile: { sketchId: string; regionId: string };
  /** The rotation axis: a sketch line, or a plane (axis = plane ∩ profile plane). */
  axis: RevolveAxis;
  /** Revolve angle in degrees, as an expression (e.g. "360" or "angle/2").
   *  A full revolve is simply `angle` "360". */
  angle: string;
  /** Revolve split evenly to both sides of the profile plane (the solid spans
   *  −angle/2 .. +angle/2) instead of one direction. Irrelevant at a full 360°. */
  symmetric: boolean;
  color: number;
  opacity: number;
  hidden?: boolean;
}

/** Mirror a body across a plane, producing a new (reflected) body. The original
 *  is kept. The mirror plane is a datum / reference plane / planar face. */
export interface MirrorFeature extends FeatureBase {
  type: "mirror";
  /** The body being mirrored (the feature id that produced it). */
  targetId: string;
  /** The mirror plane. */
  plane: SketchPlaneRef;
  color: number;
  opacity: number;
  hidden?: boolean;
}

/** Sweep a sketch region (profile) along a path entity (line/arc/spline) in a
 *  sketch. A body *producer* like extrude/revolve. (Phase 6.) */
export interface SweepFeature extends FeatureBase {
  type: "sweep";
  /** The closed sketch region to sweep. */
  profile: { sketchId: string; regionId: string };
  /** The path/spine: a single open entity (line, arc, or spline) in a sketch. */
  path: { sketchId: string; entityId: string };
  color: number;
  opacity: number;
  hidden?: boolean;
}

/** Loft through two or more sketch regions (in timeline order) to make a solid.
 *  A body *producer*. (Phase 6.) */
export interface LoftFeature extends FeatureBase {
  type: "loft";
  /** Ordered closed sections to loft through (≥2). */
  profiles: { sketchId: string; regionId: string }[];
  color: number;
  opacity: number;
  hidden?: boolean;
}

/** A body imported from a CAD file (STEP for now). A body *producer*, like a
 *  primitive. The raw file text is stored on the feature (JSON-serializable, so
 *  it round-trips through IndexedDB / `.json`). */
export interface ImportFeature extends FeatureBase {
  type: "import";
  format: "step";
  /** Raw STEP file contents. */
  source: string;
  color: number;
  opacity: number;
  hidden?: boolean;
}

export type Feature =
  | PrimitiveFeature
  | SketchFeature
  | ExtrudeFeature
  | DressUpFeature
  | BooleanFeature
  | PlaneFeature
  | TransformFeature
  | MirrorFeature
  | RevolveFeature
  | SweepFeature
  | LoftFeature
  | ImportFeature;

export interface Variable {
  id: string;
  name: string;
  expression: string;
}

export interface Document {
  features: Feature[];
  variables: Variable[];
  /** Number of features evaluated, 0..features.length. Features at index >=
   *  rollbackIndex are "rolled back" (not regenerated). */
  rollbackIndex: number;
}
